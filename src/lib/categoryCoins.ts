export function filterCoinsByCategory(
  coins: any[] = [],
  category: keyof typeof CATEGORY_SYMBOLS,
) {
  const allowed = new Set(
    CATEGORY_SYMBOLS[category].map((s) => s.toUpperCase()),
  );
  return coins.filter((coin) => allowed.has(coin?.symbol?.toUpperCase()));
}
